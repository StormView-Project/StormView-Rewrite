// Generates src/radar-wasm/colorTables.js from LibreWXR's color_table.csv, so
// the on-device renderer colors tiles exactly like the server does.
//
//   node scripts/gen-radar-colors.mjs
//
// Pinned to a LibreWXR commit; bump LIBREWXR_REF when the server adds schemes.
import { writeFileSync } from 'node:fs';

const LIBREWXR_REF = '8d7f743cc355a780fe0d65c5e4fdd3e4cae4d24d';
const CSV_URL = `https://raw.githubusercontent.com/JoshuaKimsey/LibreWXR/${LIBREWXR_REF}/src/librewxr/colors/color_table.csv`;
const OUT = new URL('../src/radar-wasm/colorTables.js', import.meta.url);

const res = await fetch(CSV_URL);
if (!res.ok) throw new Error(`fetch ${CSV_URL}: ${res.status}`);
const [header, ...rows] = (await res.text()).trim().split(/\r?\n/).map((l) => l.split(','));

// Rows 0-127 are rain colors for dBZ -32..95; the rest are snow variants,
// which raw tiles can't use (they carry no precipitation-type mask).
const rain = rows.slice(0, 128);
if (rain.length !== 128) throw new Error(`expected 128 rain rows, got ${rain.length}`);

// Scheme IDs are the CSV's column order (librewxr/colors/schemes.py).
const tables = header.slice(1).map((name, i) => {
  const hex = rain.map((r) => r[i + 1].replace('#', '').toLowerCase()).join('');
  if (!/^[0-9a-f]{1024}$/.test(hex)) throw new Error(`bad colors for ${name}`);
  return `  ${i}: '${hex}', // ${name}`;
});

writeFileSync(OUT, `// GENERATED by scripts/gen-radar-colors.mjs -- do not edit by hand.
// Source: LibreWXR color_table.csv @ ${LIBREWXR_REF.slice(0, 7)}
// (https://github.com/JoshuaKimsey/LibreWXR, AGPL-3.0-or-later).
//
// Rain colors only, keyed by LibreWXR color scheme ID: 128 RGBA hex entries,
// one per whole dBZ from -32 to 95.  Raw tile value v maps to entry v >> 1.
export const RAIN_COLOR_TABLES = {
${tables.join('\n')}
};
`);
console.log(`wrote ${tables.length} schemes to ${OUT.pathname}`);
